package org.wso2.dpdp.accelerator.event.notifications.service.exception;

/**
 * Unchecked wrapper for failures raised by the data access layer. Keeps
 * SQLException from leaking up to callers while preserving the root cause.
 */
public class DataAccessException extends RuntimeException {

    private static final long serialVersionUID = 1L;

    public DataAccessException(String message) {
        super(message);
    }

    public DataAccessException(String message, Throwable cause) {
        super(message, cause);
    }
}
