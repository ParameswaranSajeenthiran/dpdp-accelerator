package org.wso2.dpdp.accelerator.event.notifications.dao.model;

/** Persistable structured error reported for a poll delivery. */
public class PollDeliveryError {

    private final String code;
    private final String description;

    public PollDeliveryError(String code, String description) {
        this.code = code;
        this.description = description;
    }

    public String getCode() {
        return code;
    }

    public String getDescription() {
        return description;
    }
}
